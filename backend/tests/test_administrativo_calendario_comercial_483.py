ENDPOINT = "/api/v1/administrativo/configuracion/calendario-comercial"
CIERRE = "DIA_CIERRE_COMERCIAL"
VENCIMIENTO = "DIA_VENCIMIENTO_PREDETERMINADO_CUOTAS"


def _principal() -> AuthenticatedPrincipal:
    # El código deliberadamente no es ADMINISTRADOR_SISTEMA: autoriza el grant.
    return AuthenticatedPrincipal(
        id_usuario=1,
        codigo_usuario="ROL-ALTERNATIVO",
        login="calendario-test",
        id_sesion=uuid4(),
        mecanismo_autenticacion="SESION_SERVIDOR",
        autenticado_en=datetime.now(UTC).replace(tzinfo=None),
        id_instalacion_origen_sesion=1,
        id_sucursal_operativa=None,
    )


def _grant(client):
    client.app.dependency_overrides[get_authenticated_principal] = _principal
    return patch(
        "app.api.administrative_authorization.AdministrativeAuthorizationService.authorize",
        return_value=AdministrativeAuthorizationDecision.GRANTED,
    )


def _root(db_session, version: int = 1, fixture_id: int = 483_000_001) -> None:
    # La PK es GENERATED BY DEFAULT: un ID explícito mantiene el fixture aislado
    # de la sequence global, que no retrocede con el rollback transaccional.
    db_session.execute(
        text(
            "INSERT INTO configuracion_calendario_comercial("
            "id_configuracion_calendario_comercial, version_registro) "
            "VALUES (:fixture_id, :version)"
        ),
        {"fixture_id": fixture_id, "version": version},
    )


def _historical_root(db_session, fixture_id: int) -> None:
    _root(db_session, fixture_id=fixture_id)
    db_session.execute(
        text("""
            UPDATE configuracion_calendario_comercial
               SET deleted_at = CURRENT_TIMESTAMP
             WHERE id_configuracion_calendario_comercial = :fixture_id
        """),
        {"fixture_id": fixture_id},
    )


def _value(
    db_session,
    code: str,
    value: str,
    start: str,
    end: str | None,
    *,
    current: bool = False,
) -> None:
    db_session.execute(
        text("""
            INSERT INTO valor_parametro(
                id_parametro_sistema, valor_parametro, es_valor_vigente,
                fecha_desde, fecha_hasta
            )
            SELECT id_parametro_sistema, :value, :current, :start, :end
              FROM parametro_sistema WHERE codigo_parametro = :code
        """),
        {"code": code, "value": value, "current": current, "start": start, "end": end},
    )


def _period(db_session, start: str, end: str | None, cierre=10, vencimiento=20):
    _value(db_session, CIERRE, str(cierre), start, end)
    _value(db_session, VENCIMIENTO, str(vencimiento), start, end)


def _service(db_session):
    return ObtenerConfiguracionCalendarioComercialQueryService(
        CalendarioComercialQueryRepository(db_session)
    )


def test_query_service_snapshot_temporal_sin_principal_http(db_session):
    _root(db_session)
    _period(db_session, "2026-01-01", "2026-03-01", 8, 18)
    _period(db_session, "2026-03-01", None, 12, 22)

    limite_inferior = _service(db_session).obtener(date(2026, 1, 1))
    limite_superior = _service(db_session).obtener(date(2026, 3, 1))

    assert limite_inferior.dia_cierre_comercial == 8
    assert limite_inferior.fecha_hasta == datetime(2026, 3, 1)
    assert limite_superior.dia_cierre_comercial == 12
    assert limite_superior.dia_vencimiento_predeterminado_cuotas == 22
    assert limite_superior.fecha_hasta is None
    assert limite_superior.version_agregada == 1


def test_fixture_raiz_no_consume_identity_sequence(db_session):
    sequence_name = db_session.execute(
        text("""
            SELECT pg_get_serial_sequence(
                'configuracion_calendario_comercial',
                'id_configuracion_calendario_comercial'
            )
        """)
    ).scalar_one()
    before = db_session.execute(
        text(f"SELECT last_value, is_called FROM {sequence_name}")
    ).one()

    _root(db_session, fixture_id=483_000_002)

    after = db_session.execute(
        text(f"SELECT last_value, is_called FROM {sequence_name}")
    ).one()
    assert after == before


@pytest.mark.parametrize("historical_ids", [(483_000_010,), (483_000_010, 483_000_011)])
def test_query_service_usa_unica_raiz_activa_con_historicas(
    db_session, historical_ids
):
    for fixture_id in historical_ids:
        _historical_root(db_session, fixture_id)
    _root(db_session, fixture_id=483_000_012)
    _period(db_session, "2026-01-01", None)

    snapshot = _service(db_session).obtener(date(2026, 2, 1))

    # Las históricas quedaron en versión 2 al aplicar su baja; la activa es v1.
    assert snapshot.version_agregada == 1


