def test_endpoint_incompleto_y_error_tecnico_sanitizado(client, db_session):
    with _grant(client):
        incomplete = client.get(ENDPOINT, params={"fecha_efectiva": "2026-01-01"})
    assert incomplete.status_code == 200
    assert incomplete.json() == {"ok": True, "data": {"estado": "INCOMPLETA"}}

    _root(db_session)
    _value(db_session, CIERRE, "10", "2026-01-01", None)
    with _grant(client):
        inconsistent = client.get(
            ENDPOINT, params={"fecha_efectiva": "2026-01-01"}
        )
    assert inconsistent.status_code == 500
    body = inconsistent.json()
    assert body["error_code"] == "CONFIGURACION_CALENDARIO_COMERCIAL_INCONSISTENTE"
    assert body["details"] == {}
    assert "valor_parametro" not in str(body)


@pytest.mark.parametrize("raw", ["32", "1.5"])
def test_valor_corrupto_representable_en_postgresql_es_error_tecnico(
    db_session, raw
):
    _root(db_session)
    # Simula corrupción física externa que PostgreSQL puede representar. La
    # consulta debe defenderse aun si el trigger contractual fue eludido.
    db_session.execute(
        text("ALTER TABLE valor_parametro DISABLE TRIGGER USER")
    )
    try:
        _value(db_session, CIERRE, raw, "2026-01-01", None)
        _value(db_session, VENCIMIENTO, "20", "2026-01-01", None)
    finally:
        db_session.execute(text("ALTER TABLE valor_parametro ENABLE TRIGGER USER"))

    with pytest.raises(ConfiguracionCalendarioComercialInconsistente):
        _service(db_session).obtener(date(2026, 1, 1))
