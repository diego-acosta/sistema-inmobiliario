@pytest.mark.parametrize(
    "corrupt",
    [
        "definicion_faltante",
        "definicion_incompatible",
        "raiz_faltante",
        "solo_un_valor",
        "intervalos_divergentes",
        "duplicidad_aplicable",
    ],
)
def test_query_service_diferencia_inconsistencias_tecnicas(db_session, corrupt):
    if corrupt == "definicion_faltante":
        db_session.execute(
            text("DELETE FROM parametro_sistema WHERE codigo_parametro=:code"),
            {"code": CIERRE},
        )
    elif corrupt == "definicion_incompatible":
        db_session.execute(
            text("""
                UPDATE parametro_sistema SET editable_administrativamente=false
                 WHERE codigo_parametro=:code
            """),
            {"code": CIERRE},
        )
    elif corrupt == "raiz_faltante":
        _period(db_session, "2026-01-01", None)
    else:
        _root(db_session)
        if corrupt == "solo_un_valor":
            _value(db_session, CIERRE, "10", "2026-01-01", None)
        elif corrupt == "intervalos_divergentes":
            _value(db_session, CIERRE, "10", "2026-01-01", None)
            _value(db_session, VENCIMIENTO, "20", "2026-02-01", None)
        else:
            _period(db_session, "2026-01-01", None)
            _value(db_session, CIERRE, "11", "2026-01-01", None)

    with pytest.raises(ConfiguracionCalendarioComercialInconsistente):
        _service(db_session).obtener(date(2026, 2, 1))


